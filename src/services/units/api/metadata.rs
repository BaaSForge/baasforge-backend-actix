use schemars::JsonSchema;
use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
pub enum HttpMethod {
    Get,
    Post,
    Put,
    Patch,
    Delete,
    Options,
    Head,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, Default)]
#[serde(rename_all = "camelCase")]
pub struct TypeScriptJsonSchemaPair {
    pub typescript: Option<String>,
    pub json_schema: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, Default)]
#[serde(rename_all = "camelCase")]
pub struct ApiUnitMetadata {
    // NOTE: Parameters passed by the LLM are `method` and `timeoutSeconds`; the rest are generated by the type extractor.
    pub method: Option<HttpMethod>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub timeout_seconds: Option<u32>,

    // NOTE: These are generated by the type extractor.
    pub request_body: TypeScriptJsonSchemaPair,
    pub request_params: TypeScriptJsonSchemaPair,
    pub response_body: TypeScriptJsonSchemaPair,
}
