use std::fs;
use std::path::{Path, PathBuf};

const TSGO_DIR: &str = "src/tsgo";
const TYPE_DEPS_JSON: &str = "src/tsgo/runtime-project-tsc-type-deps.json";
const SDK_DTS: &str = "src/tsgo/@sdk.d.ts";
const OUT_PATH: &str = "src/tsgo/node_modules_files.rs";
const NODE_MODULES_PREFIX: &str = "node_modules/";
const TYPESCRIPT_NODE_MODULES: &str = "src/tsgo/node_modules/@typescript";

fn main() {
    if std::env::var("CARGO_FEATURE_UNIT_TECHNICAL_REVIEWER").is_err() {
        return;
    }

    println!("cargo:rerun-if-changed={TYPE_DEPS_JSON}");
    println!("cargo:rerun-if-changed={SDK_DTS}");
    println!("cargo:rerun-if-changed={TYPESCRIPT_NODE_MODULES}");

    let mut entries: Vec<(String, String)> = Vec::new();

    let json_str = fs::read_to_string(TYPE_DEPS_JSON)
        .unwrap_or_else(|e| panic!("failed to read {TYPE_DEPS_JSON}: {e}"));
    let manifest: serde_json::Value = serde_json::from_str(&json_str)
        .unwrap_or_else(|e| panic!("failed to parse {TYPE_DEPS_JSON}: {e}"));
    let files = manifest["files"].as_array().unwrap_or_else(|| {
        panic!("{TYPE_DEPS_JSON} must contain a `files` array");
    });

    for file in files {
        let path = file
            .as_str()
            .unwrap_or_else(|| panic!("each entry in `files` must be a string"));
        push_node_modules_entry(&mut entries, path, &format!("{TYPE_DEPS_JSON} lists"));
    }

    let typescript_base = PathBuf::from(TYPESCRIPT_NODE_MODULES);
    collect_dts_files(&typescript_base, &typescript_base, &mut entries);

    entries.push(("@sdk/index.d.ts".to_string(), "@sdk.d.ts".to_string()));

    entries.sort_by(|a, b| a.0.cmp(&b.0));
    entries.dedup_by(|a, b| a.0 == b.0);

    let mut code = String::from(
        "// @generated — DO NOT EDIT.\n\
         // This file is regenerated by build.rs on every build.\n\
         // Runtime type deps: runtime-project-tsc-type-deps.json; tsgo libs: node_modules/@typescript/**; @sdk.d.ts.\n\
         pub static NODE_MODULES_FILE_DATA: &[(&str, &str)] = &[\n",
    );

    for (rel_path, include_path) in &entries {
        code.push_str(&format!(
            "    ({:?}, include_str!({:?})),\n",
            rel_path, include_path
        ));
    }
    code.push_str("];\n");

    fs::write(OUT_PATH, code).expect("failed to write generated type file");
}

fn push_node_modules_entry(entries: &mut Vec<(String, String)>, path: &str, context: &str) {
    let abs = PathBuf::from(TSGO_DIR).join(path);
    if !abs.is_file() {
        panic!(
            "{context} `{path}` but it does not exist at `{}`",
            abs.display()
        );
    }
    println!("cargo:rerun-if-changed={}", abs.display());

    let rel_path = path
        .strip_prefix(NODE_MODULES_PREFIX)
        .unwrap_or_else(|| {
            panic!(
                "{context} `{path}` but it must start with `{NODE_MODULES_PREFIX}`"
            );
        })
        .to_string();

    entries.push((rel_path, path.to_string()));
}

fn collect_dts_files(base: &Path, dir: &Path, entries: &mut Vec<(String, String)>) {
    let read_dir = match fs::read_dir(dir) {
        Ok(rd) => rd,
        Err(_) => return,
    };

    for entry in read_dir.flatten() {
        let path = entry.path();

        if path.is_dir() {
            collect_dts_files(base, &path, entries);
        } else {
            let is_dts = path
                .file_name()
                .and_then(|n| n.to_str())
                .is_some_and(|s| s.ends_with(".d.ts"));

            if is_dts {
                if let Some(path_str) = path.to_str() {
                    println!("cargo:rerun-if-changed={path_str}");
                }

                if let Ok(rel) = path.strip_prefix(base) {
                    let rel_str = rel.to_string_lossy().replace('\\', "/");
                    let rel_path = format!("@typescript/{rel_str}");
                    let include_path = format!("node_modules/{rel_path}");
                    entries.push((rel_path, include_path));
                }
            }
        }
    }
}
